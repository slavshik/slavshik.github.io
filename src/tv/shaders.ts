/*
 * Шейдер белого шума.
 *
 * Аплоад DataTexture каждый кадр — это генерация массива на CPU плюс
 * texSubImage2D шестьдесят раз в секунду. Шейдер даёт то же самое даром и
 * сразу с развёрткой и виньеткой.
 */

export const SCREEN_VERT = /* glsl */ `
  varying vec2 vUv;
  void main() {
    vUv = uv;
    gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
  }
`;

export const SCREEN_FRAG = /* glsl */ `
  varying vec2 vUv;
  uniform float uTime, uIntensity, uRoll, uTexMix;
  uniform vec3  uAccent;
  uniform sampler2D uTex;

  float hash(vec2 p) {
    p = fract(p * vec2(443.897, 441.423));
    p += dot(p, p.yx + 19.19);
    return fract((p.x + p.y) * p.x);
  }

  void main() {
    vec2 uv = vec2(vUv.x, fract(vUv.y + uRoll));

    // Зерно крупное и квантованное по времени: 24 кадра в секунду, как у
    // плёнки. Попиксельный шум на 60 Гц читается как цифровой мусор, а не
    // как аналоговая трубка.
    vec2  cell = floor(uv * vec2(160.0, 115.0));
    float n = hash(cell + floor(uTime * 24.0) * 7.31);

    // Широкие полосы помех, медленно ползущие вверх
    float band = smoothstep(0.87, 1.0, sin((uv.y + uTime * 0.07) * 84.0) * 0.5 + 0.5);
    n = mix(n, min(n * 1.5, 1.0), band);

    // Строчная развёртка. Под передачей она слабее: полосы, которые на снегу
    // читаются фактурой трубки, поверх лица работают решёткой. При uTexMix = 0
    // amp равен прежним 0.16, то есть формула та же до последнего бита.
    float amp = mix(0.16, 0.085, uTexMix);
    float scan = (1.0 - amp) + amp * sin(uv.y * 560.0);

    // Шум идёт до самого края стекла. Виньетка осталась только как намёк на
    // толщину колбы — на последних процентах ширины, не больше.
    vec2  c   = abs(uv - 0.5) * 2.0;
    float vig = smoothstep(1.02, 0.95, c.x) * smoothstep(1.02, 0.94, c.y);

    // Передача, если она пришла. Сэмплируется теми же uv, что и шум, — то
    // есть уже сорванными: срыв кадра рвёт картинку так же, как рвал снег.
    // Пока uTexMix нулевой, в uTex лежит заглушка 1×1, и текстурная выборка
    // ни на что не влияет — ветвление тут было бы дороже самой выборки.
	vec3 sig = texture2D(uTex, uv).rgb;
	// Видео проходит через светлое физическое стекло и строчную развёртку,
	// поэтому без небольшой компенсации выглядит выцветшим. Контраст и цвет
	// возвращаются только передаче: снег должен остаться нейтрально-белым.
	float sigLuma = dot(sig, vec3(0.2126, 0.7152, 0.0722));
	sig = mix(vec3(sigLuma), sig, 1.18);
	sig = (sig - 0.5) * 1.08 + 0.5;

    // Снег живёт только там, где передачи нет. Раньше он подмешивался и в
    // картинку — зерном по всему кадру и чистым шумом по углам; на лице это
    // читалось не аналоговой трубкой, а грязью на стекле. Развёртка и
    // виньетка фактуру трубки держат и без него.
    //
    // Порог тут ровно один — uTexMix: при нуле mix() возвращает тот же шум,
    // что и раньше, до последнего бита, и экран без ролика не изменился.
    vec3 signal = mix(vec3(n), sig, uTexMix);

    // Снег белый: акцент уходит в свечение, а не в сам шум.
    vec3 col = signal * scan * vig;
    col = mix(col, col * uAccent * 1.6, 0.09);
    col += uAccent * 0.05 * vig;                 // ореол трубки

    gl_FragColor = vec4(col * uIntensity, 1.0);

    #include <colorspace_fragment>
  }
`;
